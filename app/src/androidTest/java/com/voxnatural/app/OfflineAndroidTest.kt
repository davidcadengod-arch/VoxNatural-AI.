package com.voxnatural.app

import android.Manifest
import android.content.pm.PackageManager
import android.media.MediaPlayer
import androidx.test.platform.app.InstrumentationRegistry
import com.tom_roush.pdfbox.android.PDFBoxResourceLoader
import com.tom_roush.pdfbox.pdmodel.PDDocument
import com.tom_roush.pdfbox.pdmodel.PDPage
import com.tom_roush.pdfbox.pdmodel.PDPageContentStream
import com.tom_roush.pdfbox.pdmodel.font.PDType1Font
import java.io.File
import java.util.zip.ZipEntry
import java.util.zip.ZipOutputStream
import org.junit.Assert.*
import org.junit.Test

class OfflineAndroidTest {
 private val context = InstrumentationRegistry.getInstrumentation().targetContext

 private fun withFixture(extension: String, test: (File) -> Unit) {
  val file = File.createTempFile("vox-test-", ".$extension", context.cacheDir)
  try {
   test(file)
  } finally {
   file.delete()
  }
 }

 @Test fun readsPdfWithDigitalText() = withFixture("pdf") { file ->
  PDFBoxResourceLoader.init(context)
  val phrase = "El médico explicó la recuperación."
  PDDocument().use { pdf ->
   val page = PDPage()
   pdf.addPage(page)
   PDPageContentStream(pdf, page).use { stream ->
    stream.beginText()
    stream.setFont(PDType1Font.HELVETICA, 12f)
    stream.newLineAtOffset(40f, 700f)
    stream.showText(phrase)
    stream.endText()
   }
   pdf.save(file)
  }
  assertEquals(phrase, DocumentText.read(file, "informe.PDF").trim())
 }

 @Test fun readsDocxParagraphsAndTxtAccents() = withFixture("docx") { file ->
  ZipOutputStream(file.outputStream()).use { zip ->
   zip.putNextEntry(ZipEntry("word/document.xml"))
   zip.write(
    """<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main"><w:body>
     <w:p><w:r><w:t>La niña</w:t><w:tab/><w:t>llegó.</w:t></w:r></w:p>
     <w:p><w:r><w:t>2,5 mg</w:t><w:br/><w:t>de medicación.</w:t></w:r></w:p>
     </w:body></w:document>""".toByteArray()
   )
   zip.closeEntry()
  }
  val expected = "La niña\tllegó.\n2,5 mg\nde medicación.\n"
  assertEquals(expected, DocumentText.read(file, "informe.docx"))
  file.writeText(expected)
  assertEquals(expected, DocumentText.read(file, "informe.txt"))
 }

 @Test fun rejectsCorruptDocumentsAndBlankText() = withFixture("bin") { file ->
  PDFBoxResourceLoader.init(context)
  file.writeText("Esto no es un PDF ni un DOCX.")
  assertThrows(Exception::class.java) { DocumentText.read(file, "corrupto.pdf") }
  assertThrows(IllegalStateException::class.java) { DocumentText.read(file, "corrupto.docx") }
  file.writeText(" \n\t")
  assertThrows(IllegalArgumentException::class.java) { DocumentText.read(file, "vacío.txt") }
 }

 @Suppress("DEPRECATION")
 @Test fun appDoesNotRequestInternetPermission() {
  val info = context.packageManager.getPackageInfo(context.packageName, PackageManager.GET_PERMISSIONS)
  assertFalse(info.requestedPermissions.orEmpty().contains(Manifest.permission.INTERNET))
 }

 @Test fun synthesizesKokoro() = synthesize(28)
 @Test fun synthesizesPiper() = synthesize(100)
 @Test fun synthesizesPocket() = synthesize(300)
 @Test fun synthesizesSupertonic() = synthesize(200)

 private fun synthesize(sid: Int) = withFixture("wav") { wav ->
  val text = "¿La niña recibió 2,5 miligramos? ¡Sí! El médico explicó la recuperación."
  NeuralVoice(context, sid).use { voice -> voice.generate(text, wav) }
  assertTrue("Invalid PCM generated by voice $sid", validNeuralWav(wav))
  assertPlayable(wav)
  withFixture("mp3") { mp3 ->
   Mp3Encoder.encode(wav, mp3)
   assertTrue("Empty MP3 generated from voice $sid", mp3.length() > 1024)
   assertPlayable(mp3)
  }
 }

 private fun assertPlayable(file: File) {
  val player = MediaPlayer()
  try {
   player.setDataSource(file.absolutePath)
   player.prepare()
   assertTrue("Audio must be at least one second: ${file.extension}", player.duration >= 1000)
  } finally {
   player.release()
  }
 }
}
